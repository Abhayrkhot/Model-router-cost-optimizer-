"""Build docs/RESULTS.md and results/summary.json from the per-split result files.

Every number in the README comes from here, so the docs can be regenerated from `results/`.
"""

from __future__ import annotations

import json
import math
import statistics
from pathlib import Path
from typing import Any

ROUTERS = ["knn+mlp", "mlp", "knn", "linear", "tfidf"]
BASELINES = ["single-model", "length-rule", "oracle"]
LABEL = {
    "knn+mlp": "kNN + MLP",
    "mlp": "MLP",
    "knn": "kNN",
    "linear": "Logistic",
    "tfidf": "TF-IDF ridge",
    "single-model": "Best mix of single models",
    "length-rule": "Old length rule",
    "oracle": "Oracle",
}
REF = "GPT-4 Turbo"


def _load(results: Path, pattern: str) -> list[dict[str, Any]]:
    return [json.loads(p.read_text()) for p in sorted(results.glob(pattern))]


def _get(d: Any, *path: str) -> float:
    for k in path:
        if d is None or k not in d:
            return float("nan")
        d = d[k]
    return float("nan") if d is None else float(d)


def _agg(values: list[float]) -> tuple[float, float]:
    vals = [v for v in values if not math.isnan(v) and math.isfinite(v)]
    if not vals:
        return float("nan"), float("nan")
    return statistics.fmean(vals), (statistics.stdev(vals) if len(vals) > 1 else 0.0)


def _fmt(mean: float, sd: float, pct: bool = False, digits: int = 3) -> str:
    if math.isnan(mean):
        return "–"
    if pct:
        s = f"{100 * mean:.1f}%"
        return s if sd == 0 or math.isnan(sd) else f"{s} ± {100 * sd:.1f}"
    s = f"{mean:.{digits}f}"
    return s if sd == 0 or math.isnan(sd) else f"{s} ± {sd:.{digits}f}"


def _metric(runs: list[dict[str, Any]], router: str, *path: str) -> tuple[float, float]:
    return _agg([_get(r["routers"].get(router, {}).get("metrics"), *path) for r in runs])


def build(results: Path, dataset_manifest: Path) -> tuple[str, dict[str, Any]]:
    rand = _load(results, "random-s*.json")
    lofo = _load(results, "lofo-*.json")
    summary: dict[str, Any] = {"seeds": [r["split"] for r in rand]}
    lines: list[str] = ["# Results", ""]
    lines += [
        "Generated by `modelrouter report` from `results/*.json`. Random splits are stratified "
        "70/10/20 by benchmark; numbers are mean ± sd over "
        f"{len(rand)} seeds unless noted. *Hull* values allow randomised mixing of two operating "
        "points (how RouterBench scores routers); *calibrated* values pick λ on the validation "
        f"set and report what that λ does on test. Reference model: {REF}.",
        "",
    ]

    man = json.loads(dataset_manifest.read_text())
    lines += ["## Data", ""]
    lines += [
        f"{man['rows_out']:,} prompts × {len(man['models'])} models "
        f"(RouterBench 0-shot @ `{man['source']['routerbench_revision'][:7]}`). "
        f"Dropped: {man['dropped']}.",
        "",
        "| Family | Prompts |",
        "|---|---:|",
    ]
    lines += [f"| {k} | {v:,} |" for k, v in man["families"].items()]
    g = man["gsm8k_regrade"]["per_model"]
    lines += [
        "",
        "GSM8K re-graded by exact match (RouterBench's own score is a 5-level grade):",
        "",
        "| Model | RouterBench score | Exact match |",
        "|---|---:|---:|",
    ]
    lines += [
        f"| {m} | {v['orig_mean']:.3f} | {v['exact_match_acc']:.3f} |"
        for m, v in sorted(g.items(), key=lambda kv: -kv[1]["exact_match_acc"])
    ]

    s0 = rand[0]
    lines += ["", f"## Single models ({s0['split']} test set, {s0['sizes']['test']:,} prompts)", ""]
    lines += ["| Model | Quality | Cost / 1k prompts |", "|---|---:|---:|"]
    for m, v in sorted(s0["single_models"].items(), key=lambda kv: -kv[1]["quality"]):
        lines.append(f"| {m} | {v['quality']:.3f} | ${1000 * v['cost']:.3f} |")

    # --- main table: quality at budgets ---------------------------------------------------
    lines += ["", "## Quality at a fixed budget (hull)", ""]
    lines += [f"Budget as a share of {REF}'s cost on the same prompts.", ""]
    budgets = ["0.05", "0.1", "0.2", "0.5"]
    lines += ["| Policy | " + " | ".join(f"{float(b):.0%}" for b in budgets) + " |"]
    lines += ["|---|" + "---:|" * len(budgets)]
    table_budget: dict[str, dict[str, Any]] = {}
    for name in [*ROUTERS, "single-model", "oracle"]:
        cells = []
        for b in budgets:
            m, sd = _metric(rand, name, "budgets", b, "quality_hull")
            cells.append(_fmt(m, sd))
            table_budget.setdefault(name, {})[b] = [m, sd]
        lines.append(f"| {LABEL[name]} | " + " | ".join(cells) + " |")
    summary["quality_at_budget_hull"] = table_budget

    # --- cost to reach a share of the reference quality --------------------------------------
    lines += ["", f"## Cost to reach a share of {REF}'s quality", ""]
    lines += [
        f"Share of {REF}'s cost. Hull: read off the test curve. Calibrated: λ chosen on "
        "validation for the target, then applied to test (the resulting test quality as a share "
        f"of {REF}'s is in brackets).",
        "",
        "| Policy | 90% hull | 95% hull | 98% hull | 100% hull | 95% calibrated |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    table_target: dict[str, dict[str, Any]] = {}
    for name in [*ROUTERS, "single-model", "oracle"]:
        cells = []
        for t in ("0.9", "0.95", "0.98", "1.0"):
            m, sd = _metric(rand, name, "targets", t, "cost_frac_hull")
            cells.append(_fmt(m, sd, pct=True))
            table_target.setdefault(name, {})[t] = [m, sd]
        cm, csd = _metric(rand, name, "targets", "0.95", "calibrated", "cost_frac")
        qm, _ = _metric(rand, name, "targets", "0.95", "calibrated", "quality_vs_ref")
        cal = "–" if math.isnan(cm) else f"{_fmt(cm, csd, pct=True)} [{100 * qm:.1f}%]"
        table_target[name]["0.95_calibrated"] = [cm, csd, qm]
        lines.append(f"| {LABEL[name]} | " + " | ".join(cells) + f" | {cal} |")
    summary["cost_to_target"] = table_target

    # --- bootstrap CIs (seed 0) ----------------------------------------------------------
    lines += ["", f"95% bootstrap intervals ({s0['split']}, 1,000 resamples of test prompts):", ""]
    lines += ["| Policy | cost at 95% of ref quality (point) | quality − ref at 10% of ref cost |"]
    lines += ["|---|---:|---:|"]
    for name in [*ROUTERS, "single-model"]:
        ci = s0["routers"][name]["metrics"].get("ci95") or {}
        a = ci.get("cost_frac_at_95pct_quality")
        b = ci.get("quality_minus_ref_at_10pct_cost")
        fa = f"{100 * a[0]:.1f}–{100 * a[1]:.1f}%" if a else "–"
        fb = f"{b[0]:+.3f} – {b[1]:+.3f}" if b else "–"
        lines.append(f"| {LABEL[name]} | {fa} | {fb} |")

    # --- two-model -----------------------------------------------------------------------
    tm = s0["routers"]["knn+mlp"]["metrics"]["two_model"]
    lines += ["", f"## Two models: {tm['weak']} vs {tm['strong']}", ""]
    lines += [
        "Route the top p% of prompts (by predicted quality gain) to the strong model. APGR is the "
        "average share of the quality gap recovered over p ∈ [0, 1] (random = 0.5); CPT(x) is the "
        "share of strong-model calls needed to recover x of the gap.",
        "",
        "| Policy | APGR | CPT(50%) | CPT(80%) |",
        "|---|---:|---:|---:|",
    ]
    table_two: dict[str, Any] = {}
    for name in [*ROUTERS, "length-rule", "single-model", "oracle"]:
        a = _metric(rand, name, "two_model", "apgr")
        c5 = _metric(rand, name, "two_model", "cpt50")
        c8 = _metric(rand, name, "two_model", "cpt80")
        table_two[name] = {"apgr": a, "cpt50": c5, "cpt80": c8}
        label = "Random" if name == "single-model" else LABEL[name]
        lines.append(f"| {label} | {_fmt(*a)} | {_fmt(*c5, pct=True)} | {_fmt(*c8, pct=True)} |")
    summary["two_model"] = table_two

    # --- routers detail ----------------------------------------------------------------------
    lines += ["", "## Router comparison", ""]
    lines += ["| Router | AIQ (log cost) | AIQ (linear) | Brier (test) | Fit time (s) |"]
    lines += ["|---|---:|---:|---:|---:|"]
    for name in [*ROUTERS, "single-model", "oracle"]:
        aiql = _metric(rand, name, "aiq_log")
        aiq = _metric(rand, name, "aiq")
        brier = _agg([_get(r["routers"].get(name), "brier_test") for r in rand])
        fit = _agg([_get(r["routers"].get(name), "fit_seconds") for r in rand])
        lines.append(
            f"| {LABEL[name]} | {_fmt(*aiql)} | {_fmt(*aiq)} | {_fmt(*brier, digits=4)} | "
            f"{'–' if name in BASELINES else f'{fit[0]:.0f}'} |"
        )

    # --- leave-one-benchmark-out -------------------------------------------------------
    if lofo:
        lines += ["", "## Unseen benchmarks (leave one benchmark out)", ""]
        lines += [
            "Train on every other benchmark, test on the held-out one. Single seed. This is the "
            "closer match to new production traffic.",
            "",
            "| Held out | Prompts | Router AIQ | Mix AIQ | Router q@10% | Mix q@10% | "
            "Router cost@95% | Mix cost@95% | APGR |",
            "|---|---:|---:|---:|---:|---:|---:|---:|---:|",
        ]
        table_lofo: dict[str, Any] = {}
        for r in lofo:
            fam = r["split"].removeprefix("lofo-")
            rt = r["routers"]["knn+mlp"]["metrics"]
            mx = r["routers"]["single-model"]["metrics"]
            row = {
                "n": r["sizes"]["test"],
                "aiq_router": rt["aiq_log"],
                "aiq_mix": mx["aiq_log"],
                "q10_router": _get(rt, "budgets", "0.1", "quality_hull"),
                "q10_mix": _get(mx, "budgets", "0.1", "quality_hull"),
                "c95_router": _get(rt, "targets", "0.95", "cost_frac_hull"),
                "c95_mix": _get(mx, "targets", "0.95", "cost_frac_hull"),
                "apgr": rt["two_model"]["apgr"],
            }
            table_lofo[fam] = row
            lines.append(
                f"| {fam} | {row['n']:,} | {row['aiq_router']:.3f} | {row['aiq_mix']:.3f} | "
                f"{_fmt(row['q10_router'], 0)} | {_fmt(row['q10_mix'], 0)} | "
                f"{_fmt(row['c95_router'], 0, pct=True)} | {_fmt(row['c95_mix'], 0, pct=True)} | "
                f"{row['apgr']:.3f} |"
            )
        summary["lofo"] = table_lofo

    # --- gateway --------------------------------------------------------------------------
    e2e = sorted((results / "e2e").glob("compare-*.json")) if (results / "e2e").exists() else []
    if e2e:
        lines += ["", "## Gateway end to end (replay)", ""]
        lines += [
            "Every test prompt sent through the running gateway (HTTP, micro-batched online "
            "embedding, routing, replay upstreams). Compared with the offline policy at the same λ.",
            "",
            "| λ | Requests | OK | Decisions identical | Quality gateway / offline | "
            "Cost per 1k gateway / offline |",
            "|---:|---:|---:|---:|---:|---:|",
        ]
        for p in e2e:
            c = json.loads(p.read_text())
            lam = p.stem.removeprefix("compare-lam")
            lines.append(
                f"| {lam} | {c['requests']:,} | {c['ok']:,} | {100 * c['decision_agreement']:.2f}% "
                f"| {c['gateway_quality']:.4f} / {c['offline_quality']:.4f} "
                f"| ${c['gateway_cost_per_1k_usd']:.4f} / ${c['offline_cost_per_1k_usd']:.4f} |"
            )
        summary["e2e"] = [json.loads(p.read_text()) for p in e2e]

    load = sorted((results / "load").glob("*.json")) if (results / "load").exists() else []
    if load:
        lines += ["", "## Gateway load tests", ""]
        lines += [
            "Open-loop arrivals; latency measured from each request's scheduled send time. "
            "`loadavg` is the host's 1-minute load at the end of the run (the host is shared).",
            "",
            "| Run | Target rps | Achieved | Success | p50 ms | p99 ms | Router p50 / p99 ms | "
            "Fallback-served | loadavg |",
            "|---|---:|---:|---:|---:|---:|---:|---:|---:|",
        ]
        runs = []
        for p in load:
            d = json.loads(p.read_text())
            runs.append({"name": p.stem, **{k: v for k, v in d.items() if k != "timeline"}})
            lat, rms = d["latency_ms"], d["router_ms"]
            lines.append(
                f"| {p.stem} | {d['config']['rate']:.0f} | {d['achieved_rps']:.0f} | "
                f"{100 * d['success_rate']:.2f}% | {lat['p50']:.1f} | {lat['p99']:.1f} | "
                f"{rms['p50']:.1f} / {rms['p99']:.1f} | {d['fallback_served']:,} | "
                f"{d['loadavg_1m_end']:.1f} |"
            )
        summary["load"] = runs

    return "\n".join(lines) + "\n", summary
